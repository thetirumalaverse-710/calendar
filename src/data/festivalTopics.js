/**
 * Retrieve festival topic definition by slug.
 * @param {string} slug
 * @returns {object|null}
 */
export function getFestivalTopic(slug) {
  if (!slug || typeof slug !== 'string') return null;
  const cleanSlug = slug.toLowerCase().trim();
  return FESTIVAL_TOPICS[cleanSlug] || null;
}

/**
 * Match events from the master events dataset using the exact primary topic phrase.
 * Utilizes the identical six searchable fields used by CalendarView:
 * title, titleTe, location, description, descriptionTe, vahanam.
 * Sorts results chronologically by startDate and startTime.
 *
 * @param {Array} events
 * @param {object} topic
 * @returns {Array} Matching events sorted chronologically
 */
export function matchFestivalEvents(events, topic) {
  if (!Array.isArray(events) || !topic) {
    return [];
  }

  // Rathotsavam (Wooden Chariot / Brahma Ratham) specific matching:
  // Matches actual Rathotsavam occurrences based primarily on event title.
  // Explicitly excludes Swarna Rathotsavam / Swarna Ratham / Golden Chariot,
  // and prevents parent festival begin events from appearing merely because
  // their vahanam/description mentions a future Rathotsavam date.
  if (topic.slug === 'rathotsavam') {
    return events
      .filter(evt => {
        if (!evt) return false;
        const title = (evt.title || '').toLowerCase();
        const titleTe = (evt.titleTe || '').toLowerCase();

        // 1. Must match Rathotsavam or Brahma Ratham in the event title
        const hasTitleMatch =
          title.includes('rathotsavam') ||
          titleTe.includes('రథోత్సవం') ||
          title.includes('brahma ratham') ||
          titleTe.includes('బ్రహ్మరథం');

        if (!hasTitleMatch) return false;

        // 2. Explicitly exclude Swarna Rathotsavam / Swarna Ratham / Golden Chariot
        const isSwarnaRatham =
          title.includes('swarna') ||
          title.includes('golden chariot') ||
          titleTe.includes('స్వర్ణ');

        if (isSwarnaRatham) return false;

        return true;
      })
      .sort((a, b) => {
        const dateComp = (a.startDate || '').localeCompare(b.startDate || '');
        if (dateComp !== 0) return dateComp;
        const timeA = (a.startTime || a.time || '').trim();
        const timeB = (b.startTime || b.time || '').trim();
        return timeA.localeCompare(timeB);
      });
  }

  // Pavithrotsavam (Annual Purification Festival) specific matching:
  // Matches actual Pavithrotsavam occurrences primarily based on event title.
  // Supports "pavithrotsavam", "pavithrotsavams", "pavithra", and Telugu "పవిత్రోత్సవ" / "పవిత్ర".
  if (topic.slug === 'pavithrotsavam') {
    return events
      .filter(evt => {
        if (!evt) return false;
        const title = (evt.title || '').toLowerCase();
        const titleTe = (evt.titleTe || '').toLowerCase();

        return (
          title.includes('pavithrotsavam') ||
          title.includes('pavithrotsavams') ||
          title.includes('pavithra') ||
          titleTe.includes('పవిత్రోత్సవ') ||
          titleTe.includes('పవిత్ర')
        );
      })
      .sort((a, b) => {
        const dateComp = (a.startDate || '').localeCompare(b.startDate || '');
        if (dateComp !== 0) return dateComp;
        const timeA = (a.startTime || a.time || '').trim();
        const timeB = (b.startTime || b.time || '').trim();
        return timeA.localeCompare(timeB);
      });
  }

  // Brahmotsavam (Grand Celestial Festival) specific matching:
  // Matches actual Brahmotsavam occurrences primarily based on event title.
  // Supports "brahmotsav" and Telugu "బ్రహ్మోత్సవ".
  // Explicitly excludes Surya Jayanti Rathasaptami ("Mini Brahmotsavam").
  if (topic.slug === 'brahmotsavam') {
    return events
      .filter(evt => {
        if (!evt) return false;
        const title = (evt.title || '').toLowerCase();
        const titleTe = (evt.titleTe || '').toLowerCase();

        const hasTitleMatch =
          title.includes('brahmotsav') ||
          titleTe.includes('బ్రహ్మోత్సవ');

        if (!hasTitleMatch) return false;

        // Exclude Surya Jayanti / Rathasaptami single-day festival
        if (title.includes('rathasaptami') || titleTe.includes('రథసప్తమి')) {
          return false;
        }

        return true;
      })
      .sort((a, b) => {
        const dateComp = (a.startDate || '').localeCompare(b.startDate || '');
        if (dateComp !== 0) return dateComp;
        const timeA = (a.startTime || a.time || '').trim();
        const timeB = (b.startTime || b.time || '').trim();
        return timeA.localeCompare(timeB);
      });
  }

  const primaryPhrase = (topic.primaryPhrase || 'garuda vahanam').toLowerCase().trim();

  return events
    .filter(evt => {
      if (!evt) return false;
      const title = (evt.title || '').toLowerCase();
      const titleTe = (evt.titleTe || '').toLowerCase();
      const location = (evt.location || '').toLowerCase();
      const description = (evt.description || '').toLowerCase();
      const descriptionTe = (evt.descriptionTe || '').toLowerCase();
      const vahanam = (evt.vahanam || '').toLowerCase();

      return (
        title.includes(primaryPhrase) ||
        titleTe.includes(primaryPhrase) ||
        location.includes(primaryPhrase) ||
        description.includes(primaryPhrase) ||
        descriptionTe.includes(primaryPhrase) ||
        vahanam.includes(primaryPhrase)
      );
    })
    .sort((a, b) => {
      const dateComp = (a.startDate || '').localeCompare(b.startDate || '');
      if (dateComp !== 0) return dateComp;
      const timeA = (a.startTime || a.time || '').trim();
      const timeB = (b.startTime || b.time || '').trim();
      return timeA.localeCompare(timeB);
    });
}
